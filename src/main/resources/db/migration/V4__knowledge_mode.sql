-- =====================================================================
-- V4：双模式面试（阶段 12 数据层）
-- 面试拆成两种互斥模式，入场时绑定、绑定后不可切换：
--   MATERIAL  = 资料面试（原模式）：模型基于简历 + JD 画像临场生成题目；
--   KNOWLEDGE = 知识库面试：从用户选定的题库抽题组成卷子，按卷出题。
--
-- 兼容性约定（重要）：存量库直接升级本脚本，新增列一律带 DEFAULT，
--   mode 默认 'MATERIAL' —— 老会话自动归到资料模式，行为与升级前完全一致。
-- =====================================================================

-- 1. interview_session：模式与知识库绑定
ALTER TABLE interview_session
    ADD COLUMN mode varchar(16) NOT NULL DEFAULT 'MATERIAL',
    ADD COLUMN kb_id int8;

-- materials 改可空：知识库模式不绑定任何资料（题从题库来，不从简历来）。
-- 写入侧仍用空串而非 NULL（见 InterviewSession 注释），改可空只为消除"无资料"的语义矛盾。
ALTER TABLE interview_session
    ALTER COLUMN materials DROP NOT NULL;

-- 2. interview_plan：卷子快照（知识库模式专用；资料模式恒为 NULL）
-- 存整段 JSON（题目序号 / 正文 / 参考答案 / 溯源 questionId）：卷子是入场时的一次性快照，
-- 题库后续增删题不影响已开场的面试——与"计划不做中途更换"同一约定。
ALTER TABLE interview_plan
    ADD COLUMN paper_json text;

-- 3. knowledge_base：知识库（一次上传 = 一个库）
CREATE TABLE knowledge_base (
    id int8 NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    name varchar(64) NOT NULL,
    description varchar(255),
    question_count int4 NOT NULL DEFAULT 0,
    source_file_name varchar(255),
    content_hash varchar(64),
    created_at timestamp NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_kb_name UNIQUE (name)
);

-- 4. question_bank：题目（归属某个知识库，库内按原序编号）
-- seq 是文档内的原题序，UNIQUE (kb_id, seq) 保证不会因重复解析把同一道题写两遍。
CREATE TABLE question_bank (
    id int8 NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    kb_id int8 NOT NULL,
    seq int4 NOT NULL,
    stem text NOT NULL,
    reference_answer text NOT NULL,
    category varchar(64),
    status varchar(16) NOT NULL DEFAULT 'ACTIVE',
    created_at timestamp NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_qb_kb_seq UNIQUE (kb_id, seq)
);
